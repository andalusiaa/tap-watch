// Writes seed/out/seed-<area>.sql, which loads an area's pubs and the beer list into D1.
//
// Usage: node seed/build-seed-sql.mjs [area-id] [--sample-listings]
// Normally run through `npm run db:seed:local` or `npm run db:seed:remote`.
//
// Safe to run again: rows are updated in place, and pubs or beers you have removed from
// the seed files are hidden (is_active = 0), not deleted.
//
// --sample-listings replaces the area's tap lists with INVENTED ones, but only while the
// area is marked as sample data (areas.is_sample = 1). Once real data is in, it does nothing.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { normalise, validateBeers } from './lib/beers.mjs';
import { parseCsv } from './lib/csv.mjs';
import { sampleListings } from './lib/sample.mjs';

const seedDir = new URL('.', import.meta.url);
const args = process.argv.slice(2);
const withSample = args.includes('--sample-listings');
const areaId = args.find((a) => !a.startsWith('--')) ?? 'e17';
const readJson = async (name) => JSON.parse(await readFile(new URL(name, seedDir), 'utf8'));

const area = (await readJson('areas.json')).find((a) => a.id === areaId);
if (!area) throw new Error(`No area "${areaId}" in seed/areas.json`);
const operators = await readJson('operators.json');
const beers = await readJson('beers.json');
validateBeers(beers);

const pubs = parseCsv(await readFile(new URL(`pubs-${area.id}.review.csv`, seedDir), 'utf8')).filter(
  (r) => r.include.toLowerCase() === 'yes',
);
const operatorIds = new Set(operators.map((o) => o.id));
for (const p of pubs) {
  if (p.operator_id && !operatorIds.has(p.operator_id)) {
    throw new Error(`${p.id}: operator_id "${p.operator_id}" is not in seed/operators.json`);
  }
}

/** SQL literal. Strings are quoted with single quotes doubled. */
function q(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Not a number: ${value}`);
    return String(value);
  }
  return `'${String(value).replaceAll("'", "''")}'`;
}
const list = (values) => values.map(q).join(', ');
const rows = (items, toValues) => items.map((item) => `  (${list(toValues(item))})`).join(',\n');

const now = new Date().toISOString();
const isSampleArea = `EXISTS (SELECT 1 FROM areas WHERE id = ${q(area.id)} AND is_sample = 1)`;
const sql = [];

sql.push(`-- Generated by seed/build-seed-sql.mjs on ${now}. Do not edit by hand.`);

sql.push(`INSERT INTO areas (id, name, postcode_district, borough, centre_lat, centre_lng, bbox, is_sample)
VALUES (${list([area.id, area.name, area.postcode_district, area.borough, area.centre_lat, area.centre_lng, JSON.stringify(area.bbox), withSample])})
ON CONFLICT (id) DO UPDATE SET name = excluded.name, postcode_district = excluded.postcode_district,
  borough = excluded.borough, centre_lat = excluded.centre_lat, centre_lng = excluded.centre_lng, bbox = excluded.bbox;`);

sql.push(`INSERT INTO operators (id, name, type) VALUES
${rows(operators, (o) => [o.id, o.name, o.type])}
ON CONFLICT (id) DO UPDATE SET name = excluded.name, type = excluded.type;`);

sql.push(`INSERT INTO beers (id, name, brewery, category, abv, is_alcohol_free, is_regular, is_active) VALUES
${rows(beers, (b) => [b.id, b.name, b.brewery, b.category, b.abv ?? null, b.is_alcohol_free, true, true])}
ON CONFLICT (id) DO UPDATE SET name = excluded.name, brewery = excluded.brewery, category = excluded.category,
  abv = excluded.abv, is_alcohol_free = excluded.is_alcohol_free, is_active = 1;`);
sql.push(`UPDATE beers SET is_active = 0 WHERE id NOT IN (${list(beers.map((b) => b.id))});`);

const aliases = beers.flatMap((b) => b.aliases.map((a) => [normalise(a), b.id]));
sql.push(`DELETE FROM beer_aliases;`);
if (aliases.length) sql.push(`INSERT INTO beer_aliases (alias, beer_id) VALUES\n${rows(aliases, (a) => a)};`);

sql.push(`INSERT INTO pubs (id, osm_id, area_id, name, address, postcode, venue_type, lat, lng, operator_id, is_active, updated_at) VALUES
${rows(pubs, (p) => [p.id, p.osm_id || null, area.id, p.name, p.address, p.postcode, 'pub', Number(p.lat), Number(p.lng), p.operator_id || null, true, now])}
ON CONFLICT (id) DO UPDATE SET osm_id = excluded.osm_id, name = excluded.name, address = excluded.address,
  postcode = excluded.postcode, lat = excluded.lat, lng = excluded.lng, operator_id = excluded.operator_id,
  is_active = 1, updated_at = excluded.updated_at;`);
sql.push(`UPDATE pubs SET is_active = 0, updated_at = ${q(now)}
WHERE area_id = ${q(area.id)} AND is_active = 1 AND id NOT IN (${list(pubs.map((p) => p.id))});`);

if (withSample) {
  const listings = sampleListings(pubs, beers, Date.now());
  sql.push(`-- Sample tap lists (only while the area is marked as sample data).
DELETE FROM listings WHERE pub_id IN (SELECT id FROM pubs WHERE area_id = ${q(area.id)}) AND ${isSampleArea};`);
  sql.push(`INSERT INTO listings (pub_id, beer_id, dispense, status, source, last_confirmed_at, reported_gone_at)
SELECT column1, column2, column3, column4, column5, column6, column7 FROM (VALUES
${rows(listings, (l) => [l.pub_id, l.beer_id, l.dispense, l.status, l.source, l.last_confirmed_at, l.reported_gone_at])}
) WHERE ${isSampleArea};`);
}

sql.push(`INSERT INTO snapshot_cache (area_id, version) VALUES (${q(area.id)}, 2)
ON CONFLICT (area_id) DO UPDATE SET version = version + 1;`);

await mkdir(new URL('out/', seedDir), { recursive: true });
const outName = `out/seed-${area.id}.sql`;
await writeFile(new URL(outName, seedDir), sql.join('\n\n') + '\n');
console.log(
  `Wrote seed/${outName}: ${pubs.length} pubs, ${beers.length} beers, ${aliases.length} aliases` +
    (withSample ? ', plus sample tap lists' : ''),
);
