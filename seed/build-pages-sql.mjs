// Loads the text of the descriptive pages from seed/pages/*.md into the pages table.
//
//   npm run db:pages:local / npm run db:pages:remote
//
// Only run this to seed a new database or to reset a page back to what is in the repo:
// day to day, these are edited on the admin Pages tab, and this would overwrite that.

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';

const seedDir = new URL('.', import.meta.url);
const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const now = new Date().toISOString();

const files = (await readdir(new URL('pages/', seedDir))).filter((f) => f.endsWith('.md'));
const rows = [];
for (const file of files) {
  const text = await readFile(new URL(`pages/${file}`, seedDir), 'utf8');
  const [first, ...rest] = text.split('\n');
  const title = (first ?? '').replace(/^#\s*/, '').trim();
  const body = rest.join('\n').trim();
  if (!title || !body) throw new Error(`${file}: needs a "# Title" line and some text`);
  rows.push(`  (${q(file.replace(/\.md$/, ''))}, ${q(title)}, ${q(body)}, ${q(now)})`);
}

const sql = `-- Generated by seed/build-pages-sql.mjs on ${now}. Do not edit by hand.
INSERT INTO pages (slug, title, body, updated_at) VALUES
${rows.join(',\n')}
ON CONFLICT (slug) DO UPDATE SET title = excluded.title, body = excluded.body, updated_at = excluded.updated_at;
`;

await mkdir(new URL('out/', seedDir), { recursive: true });
await writeFile(new URL('out/pages.sql', seedDir), sql);
console.log(`Wrote seed/out/pages.sql: ${rows.length} pages (${files.join(', ')})`);
